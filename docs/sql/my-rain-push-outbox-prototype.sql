-- ISOLATED TEST / DESIGN PROTOTYPE ONLY (2026-10-21).
-- Do not apply to production and do not connect to the active watch-rain worker.
-- Stable event keys and source episode semantics are not specified yet.
-- A successful claim grants ONE attempt, not proof of Push receipt.
--
-- In a deployment proposal the owner_id and event_key MUST be bound
-- server-side to a validated watch target and the corresponding delivery;
-- only service-role workers may write these private tables.
CREATE TABLE IF NOT EXISTS public.rain_push_event_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  target_id uuid NOT NULL,
  event_key text NOT NULL CHECK (length(event_key) BETWEEN 8 AND 256),
  notification_id bigint NOT NULL UNIQUE REFERENCES public.notification_deliveries(id) ON DELETE CASCADE,
  claimed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, target_id, event_key)
);
CREATE TABLE IF NOT EXISTS public.rain_push_subscription_attempts (
  event_claim_id bigint NOT NULL REFERENCES public.rain_push_event_claims(id) ON DELETE CASCADE,
  subscription_id uuid NOT NULL,
  state text NOT NULL DEFAULT 'CLAIMED'
    CHECK (state IN ('CLAIMED','ACCEPTED','FAILED_TERMINAL','UNCERTAIN')),
  claimed_at timestamptz NOT NULL DEFAULT now(),
  settled_at timestamptz,
  PRIMARY KEY (event_claim_id, subscription_id)
);
ALTER TABLE public.rain_push_event_claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rain_push_subscription_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.rain_push_event_claims FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.rain_push_subscription_attempts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.rain_push_event_claims_id_seq FROM PUBLIC, anon, authenticated;

